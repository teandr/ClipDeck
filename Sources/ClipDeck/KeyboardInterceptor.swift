import AppKit
import CoreGraphics
import ClipDeckCore

/// The event tap and all callbacks run on the main CFRunLoop. Closures are
/// deliberately synchronous: a command must be swallowed before the app can
/// insert anything. The coordinator defers UI and pasteboard work until after
/// this callback returns. No clipboard contents are read here.
final class KeyboardInterceptor {
    static let syntheticEventMarker: Int64 = 0x434C49504445434B

    /// Return true to consume the keydown; false to forward the native command.
    var onShortcut: ((InteractionState.Shortcut, Bool) -> Bool)?
    var onSelectSlot: ((Int) -> Void)?
    var onCancel: (() -> Void)?
    var onMouseDown: ((CGPoint) -> Void)?
    /// Lets the coordinator cancel a delayed paste if the user starts editing.
    var onUserKeyDown: (() -> Void)?
    var onTapDisabled: (() -> Void)?
    var isChoosingSlot: (() -> Bool)?

    private var tap: CFMachPort?
    private var runLoopSource: CFRunLoopSource?
    private var consumedKeys = Set<Int64>()

    var isRunning: Bool {
        guard let tap else { return false }
        return CGEvent.tapIsEnabled(tap: tap)
    }

    @discardableResult
    func start() -> Bool {
        precondition(Thread.isMainThread)
        if isRunning { return true }
        stop()
        let types: [CGEventType] = [
            .keyDown, .keyUp, .leftMouseDown, .rightMouseDown, .otherMouseDown
        ]
        let mask = types.reduce(CGEventMask(0)) { $0 | (CGEventMask(1) << $1.rawValue) }
        let callback: CGEventTapCallBack = { _, type, event, context in
            guard let context else { return Unmanaged.passUnretained(event) }
            return Unmanaged<KeyboardInterceptor>.fromOpaque(context)
                .takeUnretainedValue().receive(type: type, event: event)
        }
        guard let createdTap = CGEvent.tapCreate(
            tap: .cgSessionEventTap,
            place: .headInsertEventTap,
            options: .defaultTap,
            eventsOfInterest: mask,
            callback: callback,
            userInfo: Unmanaged.passUnretained(self).toOpaque()
        ) else { return false }
        guard let source = CFMachPortCreateRunLoopSource(kCFAllocatorDefault, createdTap, 0) else {
            CFMachPortInvalidate(createdTap)
            return false
        }
        tap = createdTap
        runLoopSource = source
        CFRunLoopAddSource(CFRunLoopGetMain(), source, .commonModes)
        CGEvent.tapEnable(tap: createdTap, enable: true)
        return CGEvent.tapIsEnabled(tap: createdTap)
    }

    func stop() {
        precondition(Thread.isMainThread)
        if let tap { CGEvent.tapEnable(tap: tap, enable: false) }
        if let runLoopSource {
            CFRunLoopRemoveSource(CFRunLoopGetMain(), runLoopSource, .commonModes)
            CFRunLoopSourceInvalidate(runLoopSource)
        }
        if let tap { CFMachPortInvalidate(tap) }
        tap = nil
        runLoopSource = nil
        consumedKeys.removeAll()
    }

    private func receive(type: CGEventType, event: CGEvent) -> Unmanaged<CGEvent>? {
        if type == .tapDisabledByTimeout || type == .tapDisabledByUserInput {
            consumedKeys.removeAll()
            if let tap { CGEvent.tapEnable(tap: tap, enable: true) }
            onTapDisabled?()
            return Unmanaged.passUnretained(event)
        }
        // Do not capture the paste event generated by this utility itself.
        if event.getIntegerValueField(.eventSourceUserData) == Self.syntheticEventMarker {
            return Unmanaged.passUnretained(event)
        }
        if type == .leftMouseDown || type == .rightMouseDown || type == .otherMouseDown {
            onMouseDown?(event.location)
            return Unmanaged.passUnretained(event)
        }

        let code = event.getIntegerValueField(.keyboardEventKeycode)
        if type == .keyUp {
            // Swallow the matching keyup even after the selection has closed.
            return consumedKeys.remove(code) == nil ? Unmanaged.passUnretained(event) : nil
        }
        guard type == .keyDown else { return Unmanaged.passUnretained(event) }
        let isRepeat = event.getIntegerValueField(.keyboardEventAutorepeat) != 0
        if isRepeat && consumedKeys.contains(code) { return nil }
        if !isRepeat { onUserKeyDown?() }

        let relevant: CGEventFlags = [.maskCommand, .maskShift, .maskControl, .maskAlternate]
        let modifiers = event.flags.intersection(relevant)
        let commandOnly = modifiers == .maskCommand
        // Hardware key positions also work with a Russian keyboard layout.
        if commandOnly && (code == 8 || code == 9) {
            let shortcut: InteractionState.Shortcut = code == 8 ? .copy : .paste
            if onShortcut?(shortcut, isRepeat) == true {
                // A repeat after a forwarded native Copy has no swallowed
                // initial down. Its eventual up must still reach that app.
                if !isRepeat { consumedKeys.insert(code) }
                return nil
            }
            return Unmanaged.passUnretained(event)
        }

        if isChoosingSlot?() == true {
            if code == 53 { // Escape
                if !isRepeat {
                    consumedKeys.insert(code)
                    onCancel?()
                }
                return nil
            }
            if modifiers.isEmpty || commandOnly, let slot = Self.slotForKeyCode[code] {
                if !isRepeat {
                    consumedKeys.insert(code)
                    onSelectSlot?(slot)
                }
                return nil
            }
            // Editing continues naturally after any unrelated key. Modifier
            // changes alone are not in the event mask and do not dismiss it.
            onCancel?()
        }
        return Unmanaged.passUnretained(event)
    }

    private static let slotForKeyCode: [Int64: Int] = [
        18: 0, 19: 1, 20: 2, 21: 3, 23: 4, 22: 5, 26: 6, 28: 7, 25: 8, 29: 9,
        83: 0, 84: 1, 85: 2, 86: 3, 87: 4, 88: 5, 89: 6, 91: 7, 92: 8, 82: 9
    ]
}
