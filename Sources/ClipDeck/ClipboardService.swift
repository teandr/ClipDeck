import AppKit
import ClipDeckCore
import Foundation

/// Materializes pasteboard data for explicit copies and the visible system cell.
/// All read I/O is serialized; only value snapshots cross back to main. Paste
/// commits run on main after prior read work drains, with a live validity check
/// immediately before touching the system clipboard.
/// Nothing is written to disk, logged, or sent over the network.
final class ClipboardService {
    enum CurrentReadResult {
        case snapshot(ClipboardPayload, preview: String, kind: String)
        case empty
        case unavailable(ClipboardError)
        case changed
    }

    private struct CaptureJob {
        let baseline: Int
        let deadline: DispatchTime
        let completion: (Result<ClipboardPayload, ClipboardError>) -> Void
        var observedChange: Int?
        var observedAt: DispatchTime?
    }

    private enum Attempt {
        case retry
        case empty
        case success(ClipboardPayload)
        case failure(ClipboardError)
    }

    /// Cancellation must not sit behind a synchronous, slow pasteboard provider.
    /// Only the flag is shared; pasteboard objects stay on the service queue.
    private final class CurrentReadJob {
        let id: UUID
        let generation: Int
        let deadline: DispatchTime
        let completion: (CurrentReadResult) -> Void
        var observedAt: DispatchTime?
        private let lock = NSLock()
        private var cancelled = false

        init(id: UUID, generation: Int, deadline: DispatchTime,
             completion: @escaping (CurrentReadResult) -> Void) {
            self.id = id
            self.generation = generation
            self.deadline = deadline
            self.completion = completion
        }

        var isCancelled: Bool {
            lock.lock()
            defer { lock.unlock() }
            return cancelled
        }

        func cancel() {
            lock.lock()
            cancelled = true
            lock.unlock()
        }
    }

    private let queue = DispatchQueue(label: "app.clipdeck.pasteboard", qos: .userInitiated)
    // Accessed exclusively by queue. AppKit may internally cache named handles;
    // the initializer is not a claim that NSPasteboard has thread-safe methods.
    private lazy var pasteboard = NSPasteboard(name: .general)
    private var captures: [UUID: CaptureJob] = [:]
    private var pendingMainCommits = 0
    private let currentReadsLock = NSLock()
    private var currentReads: [UUID: CurrentReadJob] = [:]
    private let maxPayloadBytes: Int
    private let captureTimeout: TimeInterval
    private let pollInterval: DispatchTimeInterval = .milliseconds(25)
    private let settleNanoseconds: UInt64 = 40_000_000

    private static let sensitiveTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "net.antelle.keeweb",
        "PasswordPboardType"
    ]

    private static let filePromiseTypes: Set<String> = [
        "com.apple.pasteboard.promised-file-url",
        "com.apple.pasteboard.promised-file-content-type",
        "com.apple.pasteboard.promised-file-type",
        "NSFilesPromisePboardType",
        "Apple files promise pasteboard type",
        "com.apple.NSFilePromiseItemMetaData"
    ]

    init(
        maxPayloadBytes: Int = ClipboardStore.defaultMaxPayloadBytes,
        captureTimeout: TimeInterval = 2.0
    ) {
        self.maxPayloadBytes = max(0, maxPayloadBytes)
        self.captureTimeout = max(0.1, captureTimeout)
    }

    /// `baseline` is read immediately before the physical Command-C is allowed
    /// through. Unchanged clipboard contents are never treated as a new copy.
    func capture(
        id: UUID,
        baseline: Int,
        completion: @escaping (Result<ClipboardPayload, ClipboardError>) -> Void
    ) {
        queue.async { [weak self] in
            guard let self else { return }
            // ClipDeck has one selection session at a time.
            self.captures.removeAll()
            self.captures[id] = CaptureJob(
                baseline: baseline,
                deadline: .now() + self.captureTimeout,
                completion: completion,
                observedChange: nil,
                observedAt: nil
            )
            self.poll(id)
        }
    }

    func cancel(id: UUID) {
        queue.async { [weak self] in self?.captures.removeValue(forKey: id) }
    }

    /// Reads the current generation without waiting for a new Command-C and
    /// without touching normal capture jobs, saved slots, or clipboard contents.
    /// An unchanged generation is requested at most once by the system cell.
    func readCurrent(
        id: UUID,
        expectedGeneration: Int,
        completion: @escaping (CurrentReadResult) -> Void
    ) {
        cancelCurrent(id: id)
        let job = CurrentReadJob(
            id: id, generation: expectedGeneration,
            deadline: .now() + captureTimeout, completion: completion
        )
        currentReadsLock.lock()
        currentReads[id] = job
        currentReadsLock.unlock()
        queue.async { [weak self] in self?.pollCurrent(job) }
    }

    func cancelCurrent(id: UUID) {
        currentReadsLock.lock()
        let job = currentReads.removeValue(forKey: id)
        currentReadsLock.unlock()
        job?.cancel()
    }

    /// Drains earlier capture work and then schedules a guarded main-thread
    /// commit. The coordinator invalidates shouldWrite's request token on every
    /// new user command *before* it can request another capture. Consequently,
    /// stale queued writes never overwrite the result of a later native copy.
    /// The gate also defers live system-cell reads while a main commit is queued.
    ///
    /// Completion runs in the same main block as the write, so a successful
    /// caller can immediately post its marked paste key to its verified target.
    func write(
        _ payload: ClipboardPayload,
        expectedChangeCount: Int,
        shouldWrite: @escaping () -> Bool,
        completion: @escaping (Bool) -> Void
    ) {
        precondition(Thread.isMainThread)
        queue.async { [weak self] in
            guard let self else {
                DispatchQueue.main.async { completion(false) }
                return
            }
            self.captures.removeAll()
            guard (try? payload.validate(maxBytes: self.maxPayloadBytes)) != nil else {
                DispatchQueue.main.async { completion(false) }
                return
            }
            self.pendingMainCommits += 1
            DispatchQueue.main.async {
                defer {
                    self.queue.async { self.pendingMainCommits -= 1 }
                }
                guard shouldWrite() else { completion(false); return }
                let destinationBoard = NSPasteboard.general
                guard destinationBoard.changeCount == expectedChangeCount else {
                    completion(false)
                    return
                }
                let succeeded: Bool = autoreleasepool {
                    // Build the complete set before clearing anything. These
                    // native objects are created and used only on main.
                    var items: [NSPasteboardItem] = []
                    for item in payload.items {
                        let destination = NSPasteboardItem()
                        for representation in item.representations {
                            guard destination.setData(
                                representation.data,
                                forType: NSPasteboard.PasteboardType(representation.type)
                            ) else { return false }
                        }
                        items.append(destination)
                    }
                    guard !items.isEmpty, shouldWrite(),
                          destinationBoard.changeCount == expectedChangeCount else { return false }
                    destinationBoard.clearContents()
                    return destinationBoard.writeObjects(items)
                }
                completion(succeeded)
            }
        }
    }

    private func poll(_ id: UUID) {
        dispatchPrecondition(condition: .onQueue(queue))
        guard var job = captures[id] else { return }
        let now = DispatchTime.now()
        guard now < job.deadline else {
            complete(id, result: .failure(.captureTimedOut))
            return
        }
        guard pendingMainCommits == 0 else {
            schedulePoll(id)
            return
        }

        let count = pasteboard.changeCount
        guard count != job.baseline else {
            schedulePoll(id)
            return
        }

        // Avoid the short clear-then-fill gap used by some source applications.
        // A second generation during capture is retried, never merged.
        if job.observedChange != count {
            job.observedChange = count
            job.observedAt = now
            captures[id] = job
            schedulePoll(id)
            return
        }
        if let observedAt = job.observedAt,
           now.uptimeNanoseconds - observedAt.uptimeNanoseconds < settleNanoseconds {
            schedulePoll(id)
            return
        }

        let attempt = autoreleasepool { snapshot(generation: count, deadline: job.deadline) }
        switch attempt {
        case .retry, .empty:
            schedulePoll(id)
        case .failure(let error):
            complete(id, result: .failure(error))
        case .success(let payload):
            // A lazy provider's synchronous data request can itself take longer
            // than this deadline. Such a late result is discarded. The event tap
            // and app's main thread never wait for the provider here.
            guard DispatchTime.now() < job.deadline else {
                complete(id, result: .failure(.captureTimedOut))
                return
            }
            complete(id, result: .success(payload))
        }
    }

    private func schedulePoll(_ id: UUID) {
        queue.asyncAfter(deadline: .now() + pollInterval) { [weak self] in self?.poll(id) }
    }

    private func complete(_ id: UUID, result: Result<ClipboardPayload, ClipboardError>) {
        guard let job = captures.removeValue(forKey: id) else { return }
        DispatchQueue.main.async { job.completion(result) }
    }

    private func pollCurrent(_ job: CurrentReadJob) {
        dispatchPrecondition(condition: .onQueue(queue))
        guard !job.isCancelled else { return }
        let now = DispatchTime.now()
        guard now < job.deadline else {
            completeCurrent(job, result: .unavailable(.captureTimedOut))
            return
        }
        // Explicit copies have priority, and no provider read overlaps a write.
        guard captures.isEmpty, pendingMainCommits == 0 else {
            scheduleCurrentPoll(job)
            return
        }
        guard pasteboard.changeCount == job.generation else {
            completeCurrent(job, result: .changed)
            return
        }
        if job.observedAt == nil {
            job.observedAt = now
            scheduleCurrentPoll(job)
            return
        }
        if let observedAt = job.observedAt,
           now.uptimeNanoseconds - observedAt.uptimeNanoseconds < settleNanoseconds {
            scheduleCurrentPoll(job)
            return
        }

        let attempt = autoreleasepool {
            snapshot(generation: job.generation, deadline: job.deadline,
                     allowEmpty: true, isCancelled: { job.isCancelled })
        }
        guard !job.isCancelled else { return }
        guard DispatchTime.now() < job.deadline else {
            completeCurrent(job, result: .unavailable(.captureTimedOut))
            return
        }
        guard pasteboard.changeCount == job.generation else {
            completeCurrent(job, result: .changed)
            return
        }
        switch attempt {
        case .retry:
            scheduleCurrentPoll(job)
        case .empty:
            completeCurrent(job, result: .empty)
        case .failure(let error):
            completeCurrent(job, result: .unavailable(error))
        case .success(let payload):
            // File lists and text decoding also stay off the UI thread.
            let metadata = Self.describe(payload)
            guard !job.isCancelled else { return }
            guard DispatchTime.now() < job.deadline else {
                completeCurrent(job, result: .unavailable(.captureTimedOut))
                return
            }
            guard pasteboard.changeCount == job.generation else {
                completeCurrent(job, result: .changed)
                return
            }
            completeCurrent(job, result: .snapshot(payload, preview: metadata.preview,
                                                   kind: metadata.kind))
        }
    }

    private func scheduleCurrentPoll(_ job: CurrentReadJob) {
        queue.asyncAfter(deadline: .now() + pollInterval) { [weak self] in
            self?.pollCurrent(job)
        }
    }

    private func completeCurrent(_ job: CurrentReadJob, result: CurrentReadResult) {
        guard !job.isCancelled else { return }
        DispatchQueue.main.async { [weak self] in
            guard let self else { return }
            self.currentReadsLock.lock()
            let isCurrent = self.currentReads[job.id] === job
            if isCurrent { self.currentReads.removeValue(forKey: job.id) }
            self.currentReadsLock.unlock()
            guard isCurrent, !job.isCancelled else { return }
            job.completion(result)
        }
    }

    private func snapshot(
        generation: Int,
        deadline: DispatchTime,
        allowEmpty: Bool = false,
        isCancelled: () -> Bool = { false }
    ) -> Attempt {
        guard !isCancelled(), DispatchTime.now() < deadline else {
            return .failure(.captureTimedOut)
        }
        guard pasteboard.changeCount == generation else { return .retry }
        let boardTypes = pasteboard.types ?? []
        if boardTypes.contains(where: { Self.sensitiveTypes.contains($0.rawValue) }) {
            return .failure(.sensitiveContent)
        }
        guard !isCancelled(), DispatchTime.now() < deadline else {
            return .failure(.captureTimedOut)
        }
        guard let sourceItems = pasteboard.pasteboardItems, !sourceItems.isEmpty else {
            guard pasteboard.changeCount == generation else { return .retry }
            return allowEmpty && boardTypes.isEmpty ? .empty : .retry
        }
        guard sourceItems.count <= 4_096 else { return .failure(.malformedPayload) }

        // Inspect marker types before asking any provider for actual bytes.
        let allTypes = boardTypes + sourceItems.flatMap(\.types)
        if allTypes.contains(where: { Self.sensitiveTypes.contains($0.rawValue) }) {
            return .failure(.sensitiveContent)
        }
        if allowEmpty, allTypes.isEmpty {
            return pasteboard.changeCount == generation ? .empty : .retry
        }

        var payloadItems: [ClipboardPayload.Item] = []
        var totalBytes = 0
        var sawPromisedData = false

        for item in sourceItems {
            guard !isCancelled(), DispatchTime.now() < deadline else { return .failure(.captureTimedOut) }
            guard item.types.count <= 256 else { return .failure(.malformedPayload) }
            var representations: [ClipboardPayload.Representation] = []
            var seenTypes = Set<String>()

            for type in item.types {
                guard !isCancelled(), DispatchTime.now() < deadline else { return .failure(.captureTimedOut) }
                guard pasteboard.changeCount == generation else { return .retry }
                let rawType = type.rawValue
                if Self.isFilePromise(rawType) {
                    sawPromisedData = true
                    continue
                }
                guard !rawType.isEmpty, rawType.utf8.count <= 1_024 else {
                    return .failure(.malformedPayload)
                }
                guard seenTypes.insert(rawType).inserted else { continue }

                // Materialize normal representations while their source still
                // exists. Providers are never retained in saved slots. A nil
                // value may mean clear-then-fill or a slow provider: retry.
                guard let data = item.data(forType: type) else { return .retry }
                guard !isCancelled(), DispatchTime.now() < deadline else { return .failure(.captureTimedOut) }
                guard data.count <= maxPayloadBytes,
                      totalBytes <= maxPayloadBytes - data.count else {
                    return .failure(.payloadTooLarge(maxBytes: maxPayloadBytes))
                }
                totalBytes += data.count
                representations.append(.init(type: rawType, data: data))
            }

            if representations.isEmpty {
                // A missing item must not silently turn a multi-item copy into
                // a partial success. Pure file promises cannot be replayed.
                return sawPromisedData ? .failure(.unsupportedContent) : .retry
            }
            payloadItems.append(.init(representations: representations))
        }

        guard pasteboard.changeCount == generation else { return .retry }
        let payload = ClipboardPayload(items: payloadItems)
        do {
            try payload.validate(maxBytes: maxPayloadBytes)
            return .success(payload)
        } catch let error as ClipboardError {
            // Empty data can be a source still filling its declared types.
            if allowEmpty, error == .emptyPayload, totalBytes == 0 { return .empty }
            return error == .emptyPayload ? .retry : .failure(error)
        } catch {
            return .failure(.malformedPayload)
        }
    }

    private static func isFilePromise(_ type: String) -> Bool {
        filePromiseTypes.contains(type)
            || type.hasPrefix("com.apple.pasteboard.promised-file")
            || type.lowercased().contains("filepromise")
    }

    /// Builds bounded, local display metadata; never loads the referenced files.
    static func describe(_ payload: ClipboardPayload) -> (preview: String, kind: String) {
        var filenames: [String] = []
        for item in payload.items {
            if let representation = item.representations.first(where: { $0.type == "public.file-url" }),
               let raw = String(data: representation.data, encoding: .utf8),
               let url = URL(string: raw.trimmingCharacters(in: .whitespacesAndNewlines)),
               url.isFileURL {
                filenames.append(url.lastPathComponent)
            } else if let representation = item.representations.first(where: { $0.type == "NSFilenamesPboardType" }),
                      let propertyList = try? PropertyListSerialization.propertyList(
                        from: representation.data, options: [], format: nil
                      ),
                      let paths = propertyList as? [String] {
                filenames.append(contentsOf: paths.map { URL(fileURLWithPath: $0).lastPathComponent })
            }
        }
        if !filenames.isEmpty {
            let first = String(filenames[0].prefix(80))
            if filenames.count == 1 { return (first, "Файл") }
            return ("\(filenames.count) файлов · \(first)", "Файлы")
        }

        let textTypes: Set<String> = ["public.utf8-plain-text", "public.plain-text", "public.text", "NSStringPboardType"]
        for item in payload.items {
            if let representation = item.representations.first(where: { textTypes.contains($0.type) }) {
                // Only a prefix is decoded so a large clip never blocks the UI
                // while preparing a tiny cell label.
                let text = String(decoding: representation.data.prefix(4_096), as: UTF8.self)
                let preview = text.split(whereSeparator: \.isWhitespace).joined(separator: " ")
                if !preview.isEmpty { return (String(preview.prefix(80)), "Текст") }
            }
        }

        let imageTypes: Set<String> = [
            "public.png", "public.tiff", "public.jpeg", "public.heic", "public.heif",
            "com.compuserve.gif", "org.webmproject.webp", "public.webp", "public.svg-image"
        ]
        let allTypes = Set(payload.items.flatMap { $0.representations.map(\.type) })
        if !allTypes.isDisjoint(with: imageTypes) { return ("Изображение", "Изображение") }
        if allTypes.contains("com.adobe.pdf") { return ("Документ PDF", "PDF") }
        if allTypes.contains("public.rtf") || allTypes.contains("com.apple.flat-rtfd") {
            return ("Форматированный текст", "Текст")
        }
        return ("Сохранённый фрагмент", "Данные")
    }
}
